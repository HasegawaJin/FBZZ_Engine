/// @file    PlayerHit.hpp
/// @brief   プレイヤーへの一撃の «種類» と «結末»。攻撃する側と受ける側の取り決め
/// @author  Hasegawa Jin
/// @date    2026-09-04
///
/// WHY 種類を 2 つに畳むか:
///   弾けるか弾けないかは、プレイヤーがその予兆を見て «どの動作で応えるか» を決める
///   唯一の軸。踏みつけ・突進・噛みつきは弾く、衝撃波の輪は跳ぶ、ビームは走る。
///   攻撃ごとの名前 (Stomp / Charge …) を受け手へ渡すと、受け手が攻撃の表を
///   持つことになり、ボスを 1 体足すたびにプレイヤー側を触ることになる。
///
/// WHY 結末を返すか:
///   殴った側は «当たったか» だけでなく «弾かれたか» を知らないと反応できない。
///   踏みつけを弾かれたボスは脚が跳ね上がり、突進を弾かれれば転ぶ。
///   bool 1 つでは «無敵で通らなかった» と «弾き返された» が同じになる。
#pragma once

namespace sandbox {

/// この一撃は刀で弾けるか。
enum class PlayerHitKind : int {
    /// 弾けない。跳ぶ・走る・回避で応える (衝撃波の輪・ビーム・パルス・柱)。
    Unblockable = 0,
    /// 弾ける。予兆の直後に受ければ無効化して崩しが溜まる (踏みつけ・突進・噛みつき・槍)。
    Parryable,
};

/// 一撃がどう終わったか。
enum class PlayerHitResult : int {
    /// 何も起きなかった (無敵時間・死亡済み・量が 0)。
    Ignored = 0,
    /// 通った。HP が減った。
    Damaged,
    /// 回避中で当たらなかった (ジャスト回避)。
    Dodged,
    /// 刀で弾いた。
    Parried,
    /// 構えたまま受け止めた (通常ガード)。
    ///
    /// WHY 弾きと分けるか: 見返りが正反対だから。弾きは崩しゲージを溜めて盤面を
    ///     進めるが、ガードは **1 も溜めない** ─ 止めただけで、戦いは 1 ミリも
    ///     進んでいない (Docs/break-parry.md「崩すのは弾きだけ」)。同じ値で返すと、
    ///     記録も演出も «防いだ» と «崩した» を区別できなくなる。
    Guarded,
};

} // namespace sandbox
